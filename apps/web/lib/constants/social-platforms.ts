/**
 * Extract username/handle from social media URL
 */
export function extractSocialHandle(url: string, platform: SocialPlatform): string {
  try {
    const urlObj = new URL(url);
    const pathname = urlObj.pathname;

    // Remove leading and trailing slashes
    const cleanPath = pathname.replace(/^\/+|\/+$/g, '');

    // Platform-specific extraction
    switch (platform) {
      case 'instagram':
      case 'tiktok':
      case 'threads':
        // These platforms use @username format
        const username = cleanPath.split('/')[0];
        return username.startsWith('@') ? username : `@${username}`;

      case 'twitter':
        // Twitter/X uses @username format
        const twitterUsername = cleanPath.split('/')[0];
        return twitterUsername.startsWith('@') ? twitterUsername : `@${twitterUsername}`;

      case 'github':
      case 'gitlab':
        // Extract first path segment (username)
        return cleanPath.split('/')[0] || urlObj.hostname;

      case 'linkedin':
        // LinkedIn format: /in/username or /company/name
        const segments = cleanPath.split('/');
        if (segments[0] === 'in' || segments[0] === 'company') {
          return segments[1] || cleanPath;
        }
        return segments[0] || cleanPath;

      case 'youtube':
        // YouTube format: /@channel or /c/channel or /channel/UCxxx
        const ytSegments = cleanPath.split('/');
        if (ytSegments[0].startsWith('@')) {
          return ytSegments[0];
        }
        if (ytSegments[0] === 'c' || ytSegments[0] === 'channel') {
          return ytSegments[1] || cleanPath;
        }
        return ytSegments[0] || cleanPath;

      case 'behance':
      case 'dribbble':
        // Extract username
        return cleanPath.split('/')[0] || urlObj.hostname;

      case 'medium':
        // Medium format: /@username
        const mediumUsername = cleanPath.split('/')[0];
        return mediumUsername.startsWith('@') ? mediumUsername : `@${mediumUsername}`;

      case 'bluesky':
        // Bluesky format: /profile/username.bsky.social
        const bskySegments = cleanPath.split('/');
        if (bskySegments[0] === 'profile') {
          const handle = bskySegments[1] || '';
          // Remove .bsky.social suffix if present
          return handle.replace('.bsky.social', '');
        }
        return cleanPath.split('/')[0] || urlObj.hostname;

      case 'facebook':
        // Facebook format: /username or /profile.php?id=xxx
        if (cleanPath.includes('profile.php')) {
          return 'Profile';
        }
        return cleanPath.split('/')[0] || urlObj.hostname;

      case 'personal_website':
        // For personal websites, show domain name
        return urlObj.hostname.replace('www.', '');

      default:
        return cleanPath.split('/')[0] || urlObj.hostname;
    }
  } catch {
    // If URL parsing fails, return the original URL
    return url;
  }
}
